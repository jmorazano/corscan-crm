check("Mi atención 200 con solo su fila", me.status === 200 && me.json.me && !("people" in me.json) && !("summary" in me.json), me.json);
check("es su propia fila", me.json?.me?.name && me.json.me.role === "member", me.json?.me);
const meQ = await socio.api("/api/me/attention?range=day&tz=America/Argentina/Cordoba&userId=usr_att_lucia");
check("ignora userId ajeno", meQ.json?.me?.name === me.json?.me?.name && meQ.json?.me?.waitsAnswered === 0, meQ.json?.me);
const settingsForb = await socio.api("/api/settings/attention");
check("miembro → 403 en /api/settings/attention", settingsForb.status === 403);
