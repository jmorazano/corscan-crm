import { login, check, done } from "./attention-lib.mjs";
const MIN = 60_000;
const owner = await login("e2e@vocero.test", "E2eVocero2026!");
console.log("switch:", (await owner.api("/api/workspaces/switch", { method: "POST", body: { organizationId: "org_attention_e2e" } })).status);
for (const range of ["day", "week", "year"]) {
  console.log(`\n[Métricas → Equipo · ${range}]`);
  const r = await owner.api(`/api/metrics/team?range=${range}&tz=America/Argentina/Cordoba`);
  check("200", r.status === 200, r.text.slice(0, 200));
  const d = r.json; const s = d.summary;
  check("resumen 7/3/1/1/1/1", s.total === 7 && s.onTime === 3 && s.late === 1 && s.agent === 1 && s.unanswered === 1 && s.open === 1, s);
  check("mediana equipo 7,5 min", s.medianResponseMs === 7.5 * MIN, s.medianResponseMs);
  check("esperando ahora 1 (Cliente G)", d.waitingNow.length === 1 && d.waitingNow[0].contactName === "Cliente G", d.waitingNow);
  check("para revisar 2 (C tarde + F sin respuesta)", d.problems.length === 2 && d.problems.map((p) => p.contactName).sort().join() === "Cliente C,Cliente F", d.problems.map((p) => p.contactName));
  const by = Object.fromEntries(d.people.map((p) => [p.name, p]));
  const l = by["Lucía"], p = by["Pedro"], b = by["Bruno"];
  check("Lucía 3 esperas, 1 tarde, mediana 5 min", l && l.waitsAnswered === 3 && l.waitsLate === 1 && l.medianResponseMs === 5 * MIN, l);
  check("Lucía 4 mensajes en 4 conversaciones", l && l.messages === 4 && l.conversations === 4, l);
  check("Lucía 1 dispositivo solo derivaciones", l && l.push.devices === 1 && l.push.modes.join() === "handoff", l?.push);
  check("Pedro 1 espera 10 min, 1 mensaje (fallido fuera)", p && p.waitsAnswered === 1 && p.medianResponseMs === 10 * MIN && p.messages === 1, p);
  check("Pedro sin avisos", p && p.push.devices === 0, p?.push);
  check("Bruno: ya no está, 1 mensaje, nombre copiado", b && b.role === null && b.messages === 1 && b.userId === null, b);
  check("orden: Lucía primero, Bruno al final", d.people[0].name === "Lucía" && d.people.at(-1).name === "Bruno", d.people.map((x) => x.name));
  check("lateMinutes 15", d.lateMinutes === 15);
}
console.log("\n[miembro]");
